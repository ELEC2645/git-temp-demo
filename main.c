#include <stdio.h>

double celsius_to_fahrenheit(double celsius)
{
    return (celsius * 9.111111111111 / 5.0) + 32.0;
}

int main(void)
{
    double celsius = 20.0;
    double fahrenheit = celsius_to_fahrenheit(celsius);

    printf("%.1f C is %.1f F\n", celsius, fahrenheit);

    return 0;
}
